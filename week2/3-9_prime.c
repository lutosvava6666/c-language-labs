/*-----------------------------------------------------------
 * 3-9_prime.c  判断质数函数
 * 题目：编写函数判别一个整数是否是质数，要求在主函数中
 *       输入输出。
 * 说明：质数指大于 1、且只能被 1 和它本身整除的整数。
 *-----------------------------------------------------------*/
#include <stdio.h>

/* 函数：is_prime
 * 参数：n —— 待判断的整数
 * 返回：n 是质数返回 1，不是返回 0 */
int is_prime(int n)
{
    int i;

    if (n < 2)          /* 0、1 和负数都不是质数 */
        return 0;

    /* 只需用 2 ~ sqrt(n) 试除即可，超出部分成对出现 */
    for (i = 2; i * i <= n; i++) {
        if (n % i == 0)
            return 0;   /* 找到因子，不是质数 */
    }
    return 1;           /* 没有找到任何因子，是质数 */
}

int main(void)
{
    int num;

    printf("请输入一个整数：");
    if (scanf("%d", &num) != 1) {
        printf("输入无效！\n");
        return 1;
    }

    if (is_prime(num))
        printf("%d 是质数\n", num);
    else
        printf("%d 不是质数\n", num);

    return 0;
}
