/*-----------------------------------------------------------
 * 1_bonus.c  企业发放奖金提成
 * 题目：奖金根据利润 I 提成，分段计算：
 *   I <= 10万              : 10%
 *   10万 < I <= 20万       : 10万部分按10%，超出部分按7.5%
 *   20万 < I <= 40万       : 超出20万部分按5%
 *   40万 < I <= 60万       : 超出40万部分按3%
 *   60万 < I <= 100万      : 超出60万部分按1.5%
 *   I > 100万              : 超出100万部分按1%
 * 从键盘输入当月利润 I（单位：元），输出应发放的奖金总数。
 *-----------------------------------------------------------*/
#include <stdio.h>

int main(void)
{
    double profit;      /* 当月利润（元） */
    double bonus = 0.0; /* 应发奖金（元） */

    printf("请输入当月利润（单位：元）：");
    if (scanf("%lf", &profit) != 1 || profit < 0) {
        printf("输入无效！利润必须是非负数。\n");
        return 1;
    }

    /* 分段累加：先把低档部分的提成算足，再算超出部分 */
    if (profit <= 100000.0) {
        bonus = profit * 0.10;
    } else if (profit <= 200000.0) {
        bonus = 100000.0 * 0.10 + (profit - 100000.0) * 0.075;
    } else if (profit <= 400000.0) {
        bonus = 100000.0 * 0.10 + 100000.0 * 0.075
              + (profit - 200000.0) * 0.05;
    } else if (profit <= 600000.0) {
        bonus = 100000.0 * 0.10 + 100000.0 * 0.075 + 200000.0 * 0.05
              + (profit - 400000.0) * 0.03;
    } else if (profit <= 1000000.0) {
        bonus = 100000.0 * 0.10 + 100000.0 * 0.075 + 200000.0 * 0.05
              + 200000.0 * 0.03 + (profit - 600000.0) * 0.015;
    } else {
        bonus = 100000.0 * 0.10 + 100000.0 * 0.075 + 200000.0 * 0.05
              + 200000.0 * 0.03 + 400000.0 * 0.015
              + (profit - 1000000.0) * 0.01;
    }

    printf("应发放奖金总数为：%.2f 元\n", bonus);
    return 0;
}
