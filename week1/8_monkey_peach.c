/*-----------------------------------------------------------
 * 8_monkey_peach.c  猴子吃桃问题
 * 题目：猴子第一天摘下若干个桃子，当即吃了一半，还不瘾，
 *       又多吃了一个；以后每天早上都吃了前一天剩下的一半零一个。
 *       到第 10 天早上想再吃时，见只剩下一个桃子了。
 *       求第一天共摘了多少个桃子。
 * 思路：倒推。设第 n 天早上剩 x 个，则第 n-1 天早上剩：
 *       prev = (x + 1) * 2
 *       从第 10 天的 1 个倒推回第 1 天。
 *-----------------------------------------------------------*/
#include <stdio.h>

int main(void)
{
    int peach = 1;  /* 第 10 天早上剩下 1 个桃子 */
    int day;

    /* 从第 10 天倒推到第 1 天，共倒推 9 次 */
    for (day = 10; day >= 2; day--) {
        printf("第 %2d 天早上剩 %4d 个桃子\n", day, peach);
        peach = (peach + 1) * 2;    /* 前一天的桃子数 */
    }
    printf("第  1 天早上摘了 %4d 个桃子\n", peach);
    printf("\n第一天共摘了 %d 个桃子。\n", peach);

    return 0;
}
