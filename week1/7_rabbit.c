/*-----------------------------------------------------------
 * 7_rabbit.c  古典问题：兔子繁殖（Fibonacci 数列）
 * 题目：有一对兔子，从出生后第 3 个月起每个月都生一对兔子，
 *       小兔子长到第三个月后每个月又生一对兔子。
 *       假如兔子都不死，问 20 个月中每个月的兔子总数为多少？
 * 规律：第 1、2 个月为 1 对；从第 3 个月起，
 *       当月对数 = 上月对数 + 上上月对数（即 Fibonacci 数列）。
 *-----------------------------------------------------------*/
#include <stdio.h>

int main(void)
{
    /* f1 = 上上月对数，f2 = 上月对数，cur = 当月对数 */
    long long f1 = 1, f2 = 1, cur;
    int month;

    printf("月份\t兔子对数\n");
    printf("%4d\t%8lld\n", 1, f1);
    printf("%4d\t%8lld\n", 2, f2);

    /* 从第 3 个月开始迭代计算 */
    for (month = 3; month <= 20; month++) {
        cur = f1 + f2;      /* 斐波那契递推 */
        printf("%4d\t%8lld\n", month, cur);
        f1 = f2;            /* 窗口向后滑动一个月 */
        f2 = cur;
    }

    return 0;
}
