/*-----------------------------------------------------------
 * 6_multiplication_table.c  9*9 口诀表
 * 题目：输出完整的九九乘法口诀表（下三角形式）。
 *-----------------------------------------------------------*/
#include <stdio.h>

int main(void)
{
    int i, j;

    /* 外层控制行（被乘数），内层控制列（乘数），形成下三角 */
    for (i = 1; i <= 9; i++) {
        for (j = 1; j <= i; j++) {
            /* %-2d 使乘积左对齐占 2 位，\t 对齐各列 */
            printf("%d*%d=%-2d\t", j, i, i * j);
        }
        printf("\n");   /* 每行结束换行 */
    }

    return 0;
}
